const assert=require('node:assert/strict');
const {rowsOf}=require('../devtoolnext/web/transcript.js');
const rec=(id,direction,bytes)=>({id,direction,wall:1,data_base64:Buffer.from(bytes).toString('base64')});
const utf8=Buffer.from('设备 ready\r\nsecond line\n');
const split=[rec(1,'rx',utf8.subarray(0,1)),rec(2,'rx',utf8.subarray(1,4)),rec(3,'rx',utf8.subarray(4))];
const rows=rowsOf(split,'log','utf-8');
assert.deepEqual(rows.map(r=>r.text),['设备 ready','second line']);
assert.equal(rows[0].records.length,3);
assert.deepEqual(rows[0].records.map(r=>r.id),[1,2,3]);
assert.equal(rowsOf(split,'hex','utf-8').length,3);
assert.equal(rowsOf(split,'records','utf-8')[0].text,'E8');
assert.deepEqual(rowsOf([rec(1,'tx','hello\n'),rec(2,'rx','h'),rec(3,'rx','ello\n')],'log','utf-8').map(r=>r.text),['hello','hello']);
assert.deepEqual(rowsOf([rec(1,'rx','a\n\nb\r\nc')],'log','utf-8').map(r=>r.text),['a','','b','c']);
assert.equal(rowsOf([rec(1,'rx','x'.repeat(17000))],'log','utf-8')[0].truncated,true);
assert.deepEqual(rowsOf([],'log','utf-8'),[]);
const timed=rowsOf([rec(1,'rx','first\n'),{...rec(2,'rx','second\n'),wall:2}],'log','utf-8');
assert.deepEqual(timed.map(r=>r.wall),[1,2]);
assert.equal(rowsOf([rec(1,'rx','first\r'),rec(2,'rx','\nsecond')],'log','utf-8')[0].text,'first');
assert.deepEqual(rowsOf([rec(1,'rx','OK\rREADY\rFAIL\r')],'log','utf-8').map(r=>r.text),['OK','READY','FAIL']);
assert.deepEqual(rowsOf([rec(1,'rx','a\r'),rec(2,'rx','b')],'log','utf-8').map(r=>r.text),['a','b']);
assert.deepEqual(rowsOf([rec(1,'rx','a\r'),rec(2,'rx','\nb')],'log','utf-8').map(r=>r.text),['a','b']);
console.log('PASS: incremental byte chunks, Unicode, CRLF, CR-only, direction, raw evidence, line limit');
